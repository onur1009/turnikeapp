const segLen = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);

// Çizgi boyunca n noktayı eşit aralıkla yerleştirir
export const getStationPoints = (lineId, n) => {
  const pts = LINE_PATHS[lineId];
  if (!pts || n <= 0) return [];
  if (n === 1) return [pts[0]];
  const lens = pts.slice(1).map((p, i) => segLen(pts[i], p));
  const total = lens.reduce((s, l) => s + l, 0);
  const out = [];
  for (let k = 0; k < n; k++) {
    let d = (total * k) / (n - 1);
    let i = 0;
    while (i < lens.length - 1 && d > lens[i]) { d -= lens[i]; i++; }
    const t = lens[i] ? Math.min(1, d / lens[i]) : 0;
    out.push([pts[i][0] + (pts[i + 1][0] - pts[i][0]) * t, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * t]);
  }
  return out;
};

export const toPath = (pts) => pts.map((p, i) => `${i ? 'L' : 'M'}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join(' ');
